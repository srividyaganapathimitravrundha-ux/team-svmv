let currentLang = 'en';
let galleryItems = [];
let galleryIndex = 0;

const $ = s => document.querySelector(s);

function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang === 'kn' ? 'kn' : 'en';

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.dataset.i18n;

    if (translations[lang][k]) {
      el.textContent = translations[lang][k];
    }
  });

  $('#languageToggle').textContent =
    lang === 'en' ? 'ಕನ್ನಡ' : 'English';

  localStorage.setItem('svmv-lang', lang);
}

function initQRs() {
  document.querySelectorAll('.qr').forEach(el => {
    el.innerHTML = '';

    new QRCode(el, {
      text: el.dataset.qr,
      width: 150,
      height: 150,
      colorDark: '#120d0a',
      colorLight: '#ffffff',
      correctLevel: QRCode.CorrectLevel.M
    });
  });
}

function updateCountdown() {
  const start = new Date(SVMV_CONFIG.festivalStart).getTime();
  const end = new Date(SVMV_CONFIG.festivalEnd).getTime();
  const now = Date.now();

  let diff;

  if (now < start) {
    diff = start - now;

    $('#countdownMessage').textContent =
      currentLang === 'kn'
        ? 'ಗಣೇಶೋತ್ಸವ ಆರಂಭವಾಗಲು'
        : 'Ganeshotsava begins in';

  } else if (now <= end) {
    ['days', 'hours', 'minutes', 'seconds'].forEach(id => {
      $('#' + id).textContent = '00';
    });

    $('#countdownMessage').textContent =
      currentLang === 'kn'
        ? '🙏 ಗಣೇಶೋತ್ಸವ ಸಂಭ್ರಮ ನಡೆಯುತ್ತಿದೆ'
        : '🙏 The celebrations are underway';

    return;

  } else {
    ['days', 'hours', 'minutes', 'seconds'].forEach(id => {
      $('#' + id).textContent = '00';
    });

    $('#countdownMessage').textContent =
      currentLang === 'kn'
        ? '❤️ ನಮ್ಮ ಸಂಭ್ರಮದ ಭಾಗವಾಗಿದ್ದಕ್ಕಾಗಿ ಧನ್ಯವಾದಗಳು'
        : '❤️ Thank you for being part of our celebrations';

    return;
  }

  const s = Math.floor(diff / 1000);
  const d = Math.floor(s / 86400);
  const h = Math.floor((s % 86400) / 3600);
  const m = Math.floor((s % 3600) / 60);
  const sec = s % 60;

  $('#days').textContent = String(d).padStart(2, '0');
  $('#hours').textContent = String(h).padStart(2, '0');
  $('#minutes').textContent = String(m).padStart(2, '0');
  $('#seconds').textContent = String(sec).padStart(2, '0');
}

function makeUpiUrl(amount) {
  const p = new URLSearchParams({
    pa: SVMV_CONFIG.upiId,
    pn: SVMV_CONFIG.upiName,
    am: Number(amount).toFixed(2),
    cu: 'INR',
    tn: 'Team SVMV Contribution'
  });

  return 'upi://pay?' + p.toString();
}

function showPayment(name, mobile, amount) {
  const url = makeUpiUrl(amount);

  $('#paymentDetails').textContent =
    `${name} · ${mobile} · ₹${Number(amount).toLocaleString('en-IN')}`;

  $('#paymentQr').innerHTML = '';

  new QRCode($('#paymentQr'), {
    text: url,
    width: 230,
    height: 230,
    colorDark: '#120d0a',
    colorLight: '#ffffff',
    correctLevel: QRCode.CorrectLevel.H
  });

  $('#upiButton').href = url;

  $('#paymentPanel').classList.remove('hidden');

  $('#paymentPanel').scrollIntoView({
    behavior: 'smooth',
    block: 'center'
  });

  if (SVMV_CONFIG.APPS_SCRIPT_URL) {
    fetch(SVMV_CONFIG.APPS_SCRIPT_URL, {
      method: 'POST',
      mode: 'no-cors',
      headers: {
        'Content-Type': 'text/plain'
      },
      body: JSON.stringify({
        action: 'contribution',
        name,
        mobile,
        amount,
        timestamp: new Date().toISOString()
      })
    }).catch(() => {});
  }
}

function openLightbox(index) {
  galleryIndex = index;

  const item = galleryItems[index];

  if (!item) return;

  $('#lightboxImage').src = item.src;
  $('#lightboxImage').alt =
    item.caption || 'Team SVMV memory';

  $('#lightboxCaption').textContent =
    item.caption || '';

  $('#lightbox').classList.remove('hidden');

  document.body.style.overflow = 'hidden';
}

function closeLightbox() {
  $('#lightbox').classList.add('hidden');
  document.body.style.overflow = '';
}

function nextImage(dir) {
  if (!galleryItems.length) return;

  galleryIndex =
    (galleryIndex + dir + galleryItems.length) %
    galleryItems.length;

  openLightbox(galleryIndex);
}

function renderGallery(items) {
  galleryItems = items || [];

  const tabs = $('#galleryTabs');
  const grid = $('#galleryGrid');

  if (!galleryItems.length) {
    tabs.innerHTML = '';

    grid.innerHTML = `
      <div class="gallery-placeholder">
        ${translations[currentLang].galleryPlaceholder}
      </div>
    `;

    return;
  }

  // Get only years that actually have photos
  const years = [
    ...new Set(
      galleryItems
        .map(item => String(item.Year || '').trim())
        .filter(Boolean)
    )
  ];

  // Create year tabs
  tabs.innerHTML = years.map((year, index) => `
    <button
      class="gallery-tab ${index === 0 ? 'active' : ''}"
      data-year="${year}">
      ${year}
    </button>
  `).join('');

  function showYear(year) {
    const filtered = galleryItems.filter(
      item => String(item.Year || '').trim() === year
    );

    grid.innerHTML = filtered.map(item => {
      const globalIndex = galleryItems.indexOf(item);

      if (item.type === 'video') {
        return `
          <figure
            class="gallery-item gallery-video"
            data-index="${globalIndex}">
            <iframe
              src="${item.src}"
              title="${item.caption || 'Team SVMV Video'}"
              allow="autoplay; fullscreen"
              allowfullscreen
              loading="lazy">
            </iframe>
            <figcaption>
              ${item.caption || ''}
            </figcaption>
          </figure>
        `;
      }

      return `
        <figure
          class="gallery-item"
          data-index="${globalIndex}">
          <img
            src="${item.src}"
            alt="${item.caption || 'Team SVMV'}"
            loading="lazy">
          <figcaption>
            ${item.caption || ''}
          </figcaption>
        </figure>
      `;
    }).join('');

    // Open full-screen image viewer
    grid.querySelectorAll('.gallery-item').forEach(item => {
      if (item.classList.contains('gallery-video')) return;

      item.addEventListener('click', () => {
        galleryIndex = Number(item.dataset.index);
        openLightbox(galleryIndex);
      });
    });
  }

  // First available year
  showYear(years[0]);

  // Year tab clicks
  tabs.querySelectorAll('.gallery-tab').forEach(tab => {
    tab.addEventListener('click', () => {
      tabs.querySelectorAll('.gallery-tab')
        .forEach(button => button.classList.remove('active'));

      tab.classList.add('active');

      showYear(tab.dataset.year);
    });
  });
}

async function loadRemoteContent() {
  if (!SVMV_CONFIG.APPS_SCRIPT_URL) return;

  try {
    const res = await fetch(
      SVMV_CONFIG.APPS_SCRIPT_URL + '?action=site'
    );

    if (!res.ok) {
      console.warn(
        'Apps Script request failed:',
        res.status
      );

      return;
    }

    const data = await res.json();

    if (data.config) {
      Object.assign(SVMV_CONFIG, data.config);
    }

    if (Array.isArray(data.gallery)) {
      renderGallery(data.gallery);
    }

  } catch (error) {
    console.warn(
      'Google Sheets content not loaded:',
      error
    );
  }
}

